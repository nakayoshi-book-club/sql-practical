INSERT INTO ThreeElements
SELECT n, 'x',
  CASE WHEN n % 3 = 0 THEN DATE '2000-01-01' + (n % 3650) END, CASE WHEN n % 3 = 0 THEN CASE WHEN n % 2 = 0 THEN 'T' ELSE 'F' END END,
  CASE WHEN n % 3 = 1 THEN DATE '2000-01-01' + (n % 3650) END, CASE WHEN n % 3 = 1 THEN CASE WHEN n % 2 = 0 THEN 'T' ELSE 'F' END END,
  CASE WHEN n % 3 = 2 THEN DATE '2000-01-01' + (n % 3650) END, CASE WHEN n % 3 = 2 THEN CASE WHEN n % 2 = 0 THEN 'T' ELSE 'F' END END
FROM generate_series(1000, 300999) AS n;
ANALYZE;
VACUUM (INDEX_CLEANUP ON, ANALYZE);
